export type IconName = Extract<keyof typeof icons, string>;

export function Icon({ name, size = 16, ...rest }: { name: IconName; size?: number } & SVGProps<SVGSVGElement>) {
  const entry: { icon: PhosphorIcon; weight?: "fill" | "bold"; mirrored?: boolean } = icons[name];
  const Glyph = entry.icon;
  const { ref: _ref, ...props } = rest;
  return (
    <Glyph
      size={size}
      weight={entry.weight ?? "regular"}
      mirrored={entry.mirrored ?? false}
      aria-hidden="true"
      focusable="false"
      {...(props as IconProps)}
    />
  );
}
